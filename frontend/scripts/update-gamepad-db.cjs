#!/usr/bin/env node
/*
 * Regenerate js/stream/gamepadDb.js from SDL_GameControllerDB (run from
 * frontend/):  node scripts/update-gamepad-db.cjs [<commit sha>]
 *
 * The database maps controllers the browser reports without a standard
 * layout (gp.mapping !== 'standard') to the Xbox layout. Only the desktop
 * platforms are kept: Chrome Android already reorders unknown pads itself
 * (UnknownGamepadMappings), and iOS only exposes standard pads — SDL's own
 * Android and iOS entries use SDL's index scheme and would be wrong there.
 *
 * Entries are keyed by USB vendor:product, taken from the SDL GUID (bytes
 * 4-5 and 8-9, little-endian). GUIDs that carry a name instead of ids, and
 * the XInput placeholders, are dropped: the browser gives us ids, not those.
 *
 * The commit is pinned so a regeneration is a deliberate, reviewable diff.
 */
const fs = require('fs');
const path = require('path');

const DEFAULT_SHA = '5a12daa568d19344f9b6e9286ef5929833b25c7c';
const sha = process.argv[2] || DEFAULT_SHA;
const RAW = `https://raw.githubusercontent.com/mdqinc/SDL_GameControllerDB/${sha}`;
const OUT = path.resolve(__dirname, '..', 'js', 'stream', 'gamepadDb.js');

const PLATFORMS = { Windows: 'win', 'Mac OS X': 'mac', Linux: 'linux' };

// The only fields gamepadMapping.js reads; SDL also carries misc/paddle/touchpad
// buttons a virtual X360 has nowhere to put.
const TARGETS = new Set([
    'a',
    'b',
    'x',
    'y',
    'back',
    'guide',
    'start',
    'leftstick',
    'rightstick',
    'leftshoulder',
    'rightshoulder',
    'dpup',
    'dpdown',
    'dpleft',
    'dpright',
    'leftx',
    'lefty',
    'rightx',
    'righty',
    'lefttrigger',
    'righttrigger',
]);

const hex4 = (n) => n.toString(16).padStart(4, '0');

/** vid:pid from an SDL GUID, or null when the GUID does not hold USB ids. */
function idsFromGuid(guid) {
    if (!/^[0-9a-f]{32}$/i.test(guid)) return null;
    const b = (i) => parseInt(guid.substr(i * 2, 2), 16);
    const le16 = (i) => b(i) | (b(i + 1) << 8);
    // SDL only stores ids when bytes 6-7 and 10-11 are zero; otherwise the
    // GUID is the start of the device name.
    if (le16(6) !== 0 || le16(10) !== 0) return null;
    const vid = le16(4);
    const pid = le16(8);
    if (vid === 0 || pid === 0) return null;
    return `${hex4(vid)}:${hex4(pid)}`;
}

async function main() {
    const get = async (file) => {
        const res = await fetch(`${RAW}/${file}`);
        if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
        return res.text();
    };
    const text = await get('gamecontrollerdb.txt');
    // The zlib notice must travel with the data, verbatim.
    const license = (await get('LICENSE'))
        .trim()
        .split(/\r?\n/)
        .map((l) => (' *   ' + l).trimEnd())
        .join('\n');

    const db = { win: {}, mac: {}, linux: {} };
    let kept = 0;
    for (const raw of text.split(/\r?\n/)) {
        const line = raw.trim();
        if (!line || line.startsWith('#')) continue;
        const fields = line.split(',');
        const [guid, name, ...rest] = fields;
        let platform = null;
        const mapping = [];
        for (const f of rest) {
            const m = /^([+-]?)([a-z]+):(.+)$/.exec(f);
            if (!m) continue;
            if (m[2] === 'platform') {
                platform = PLATFORMS[m[3]] || null;
            } else if (TARGETS.has(m[2])) {
                mapping.push(f);
            }
        }
        if (!platform || mapping.length === 0) continue;
        const key = idsFromGuid(guid);
        if (!key) continue;
        (db[platform][key] ||= []).push([name, mapping.join(',')]);
        kept++;
    }

    const header = `/*
 * GENERATED by scripts/update-gamepad-db.cjs — do not edit by hand.
 *
 * Source: SDL_GameControllerDB @ ${sha}
 *   https://github.com/mdqinc/SDL_GameControllerDB
 * Desktop entries only (Windows, Mac OS X, Linux), keyed by vendor:product.
 * ${kept} mappings.
 *
 * SDL_GameControllerDB is distributed under the zlib license:
 *
${license}
 *
 * Altered: filtered to desktop platforms and re-keyed by vendor:product.
 */
`;
    // One entry per line keeps the regeneration diff readable.
    let body = 'export default {\n';
    for (const p of Object.keys(db)) {
        body += `    ${p}: {\n`;
        for (const key of Object.keys(db[p]).sort()) {
            body += `        '${key}': ${JSON.stringify(db[p][key])},\n`;
        }
        body += '    },\n';
    }
    body += '};\n';
    fs.writeFileSync(OUT, header + body);
    const size = fs.statSync(OUT).size;
    console.log(
        `✓ ${kept} mappings → ${path.relative(process.cwd(), OUT)} (${(size / 1024).toFixed(0)} KiB)`,
    );
}

main().catch((e) => {
    console.error('✗ ' + e.message);
    process.exit(1);
});
